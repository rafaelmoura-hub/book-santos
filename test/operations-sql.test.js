const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');

test('PostgreSQL: RLS, concorrência, auditoria e consumo atômico', async t => {
  const db = new PGlite();
  t.after(() => db.close());
  await db.exec(`
    create role anon; create role authenticated;
    create schema auth; create schema storage;
    create table auth.users(id uuid primary key);
    create function auth.uid() returns uuid language sql stable as
      $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema public,auth,storage to authenticated,anon;
    grant execute on function auth.uid() to authenticated,anon;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id bigint generated always as identity, bucket_id text,name text);
    alter table storage.objects enable row level security;
    grant select,insert on storage.objects to authenticated;
    grant usage on sequence storage.objects_id_seq to authenticated;
    create function storage.foldername(name text) returns text[] language sql immutable as $$ select string_to_array(name,'/') $$;
  `);
  const migration = name => readFileSync(path.join(__dirname, '..', 'supabase', 'migrations', name), 'utf8');
  await db.exec(migration('202610170001_book_profiles.sql'));
  await db.exec(migration('202610170002_operations.sql'));
  await db.exec(migration('202610170002_operations.sql'));
  await db.exec(migration('202610220003_pilot.sql'));
  await db.exec(migration('202610220003_pilot.sql'));
  const master = '11111111-1111-4111-8111-111111111111';
  const client = '22222222-2222-4222-8222-222222222222';
  const other = '33333333-3333-4333-8333-333333333333';
  const admin = '44444444-4444-4444-8444-444444444444';
  for (const [id, name, role, isMaster] of [[master,'Mestre','adm',true],[client,'Cliente','cliente',false],[other,'Outro','cliente',false],[admin,'Gestor','adm',false]]) {
    await db.query('insert into auth.users values($1)', [id]);
    await db.query('insert into public.book_profiles(id,nome,login,funcao,mestre) values($1,$2,$3,$4,$5)', [id,name,`${name}@test.com`,role,isMaster]);
  }
  await db.query("insert into public.book_hotel_access values($1,'Unlimited'),($2,'Unlimited'),($3,'Unique')", [client,other,admin]);
  const actor = async id => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); await db.exec('set role authenticated'); };
  const commit = changes => db.query('select public.book_commit($1::jsonb)',[JSON.stringify(changes)]);
  const change = (collection,id,data,version=0) => ({collection,id:String(id),data,version});
  const ticket = id => ({id,hotel:'Unlimited',apartamento:'1111',assunto:'Vazamento',descricao:'Torneira com vazamento',status:'Aberto'});
  await actor(client);
  await commit([change('chamados',101,ticket(101))]);
  const row = (await db.query("select * from public.book_records where id='101'")).rows[0];
  assert.equal(row.owner_id,client);
  assert.equal(row.data.criadaPorLogin,'Cliente@test.com');
  await assert.rejects(commit([change('chamados',101,ticket(101))]),error=>error.code==='PT409');
  await assert.rejects(commit([change('chamados',101,{...row.data,status:'Fechado'},1)]),error=>error.code==='42501');
  await assert.rejects(commit([change('chamados',102,{...ticket(102),hotel:'Unique'})]),error=>error.code==='42501');
  await assert.rejects(db.exec("update public.book_profiles set funcao='adm'"),error=>error.code==='42501');
  await assert.rejects(db.exec("insert into public.book_records values('chamados','evil','{}','"+client+"','Unlimited',1,now())"),error=>error.code==='42501');
  await actor(other);
  assert.equal((await db.query('select * from public.book_records')).rows.length,0);
  await actor(admin);
  assert.equal((await db.query('select * from public.book_records')).rows.length,0);
  await actor(master);
  assert.equal((await db.query('select public.book_schema_version() version')).rows[0].version,3);
  await assert.rejects(commit([change('chamados',104,{...ticket(104),apartamento:'9999'})]),error=>error.code==='22023');
  await assert.rejects(commit([change('ordensServico',204,{id:204,hotel:'Unlimited',apartamento:'1111',titulo:'Teste',status:'Aberta',vencimento:'2026-02-30'})]),error=>error.code==='22023');
  await assert.rejects(commit([change('ordensServico',204,{id:204,hotel:'Unlimited',apartamento:'1111',titulo:'Teste',status:'Aberta',vencimento:'2026-10-<img src=x onerror=alert(1)>'})]),error=>error.code==='22023');
  const inspection={id:301,hotel:'Unlimited',apartamento:'1111',data:'2026-10-22',responsavel:'Gestor',tipo:'Completa',checklist:{Sala:{Porta:'Em ordem'}},fotos:[]};
  await commit([change('vistorias',301,inspection)]);
  await assert.rejects(commit([change('vistorias',302,{...inspection,id:302,checklist:{Sala:{Porta:'inventado'}}})]),error=>error.code==='22023');
  await assert.rejects(commit([change('vistorias',302,{...inspection,id:302,data:'2026-02-30'})]),error=>error.code==='22023');
  await assert.rejects(commit([change('chamados',104,{...ticket(104),anexoData:`/api/files/${client}/Unlimited/11111111-1111-4111-8111-111111111111`})]),error=>error.code==='22023');
  const stock = {colunas:[],itens:[{id:'material',nome:'Torneira',quantidade:10,valor:2}]};
  await commit([change('estoqueBookSantos','singleton',stock)]);
  const order = (id,quantity) => ({id,hotel:'Unlimited',apartamento:'1111',titulo:'Conserto',status:'Em andamento',fechamento:{materiais:[{id:'material',quantidade:quantity}]}});
  await commit([change('ordensServico',201,order(201,4))]);
  const quantity = async () => (await db.query("select data#>'{itens,0,quantidade}' quantity from public.book_records where collection='estoqueBookSantos'")).rows[0].quantity;
  assert.equal(await quantity(),6);
  await assert.rejects(commit([change('ordensServico',201,order(201,5))]),error=>error.code==='PT409');
  assert.equal(await quantity(),6);
  await assert.rejects(commit([change('ordensServico',202,order(202,7))]),error=>error.code==='PT409');
  assert.equal(await quantity(),6);
  assert.equal((await db.query("select * from public.book_records where id='202'")).rows.length,0);
  await assert.rejects(commit([change('chamados',103,ticket(103)),change('ordensServico',203,order(203,99))]),error=>error.code==='PT409');
  assert.equal((await db.query("select * from public.book_records where id='103'")).rows.length,0);
  await commit([change('ordensServico',201,order(201,2),1)]);
  assert.equal(await quantity(),8);
  await assert.rejects(commit([change('estoqueBookSantos','singleton',{colunas:[],itens:[]},3)]),/removido/);
  const completed={...order(201,2),status:'Finalizada',fechamento:{...order(201,2).fechamento,data:'2026-10-17',executadoPorLogin:'Mestre@test.com',responsavelPagamento:'Book Santos',valorServico:5}};
  await commit([change('ordensServico',201,completed,2)]);
  const completedRow=(await db.query("select data from public.book_records where id='201'")).rows[0];
  assert.equal(completedRow.data.fechamento.custoTotal,9);
  await assert.rejects(commit([change('ordensServico',201,order(201,2),3)]),error=>error.code==='42501');
  assert.ok((await db.query('select * from public.book_audit')).rows.length>=6);
  await actor(client);
  const message={id:'m1',texto:'Olá',autorNome:'Cliente',autorTipo:'cliente',lidoAdmin:false,lidoCliente:true};
  const conversation={chamadoId:'101',hotel:'Unlimited',mensagens:[message]};
  const chatId=`${client}::101`;
  await assert.rejects(commit([change('conversasSuporte',chatId,{...conversation,mensagens:[{...message,autorTipo:'admin'}]})]),error=>error.code==='22023');
  await commit([change('conversasSuporte',chatId,conversation)]);
  await assert.rejects(commit([change('conversasSuporte',chatId,{...conversation,mensagens:[{...message,texto:'histórico adulterado'}]},1)]),error=>error.code==='42501');
  await db.query('insert into storage.objects(bucket_id,name) values($1,$2)',['book-attachments',`${client}/Unlimited/file`]);
  await assert.rejects(db.query('insert into storage.objects(bucket_id,name) values($1,$2)',['book-attachments',`${client}/Unique/file`]),error=>error.code==='42501');
  await actor(other);
  assert.equal((await db.query('select * from storage.objects')).rows.length,0);
  assert.equal((await db.query('select * from public.book_audit')).rows.length,0);
  await db.exec('reset role; set role anon');
  await assert.rejects(commit([]),error=>error.code==='42501');
});
