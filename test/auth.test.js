const { test } = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { mkdtempSync, rmSync } = require('node:fs');
const { tmpdir } = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../server/database');
const { hashPassword } = require('../server/passwords');
const { createApp } = require('../server/index');

test('autenticação, permissões, usuários e persistência', async t => {
  const folder = mkdtempSync(path.join(tmpdir(), 'book-santos-test-'));
  const filename = path.join(folder, 'test.sqlite');
  const db = openDatabase(filename);
  const password = 'Teste-seguro-1234';
  db.prepare('INSERT INTO users VALUES (?,?,?,?,?,1)').run('master', 'Administrador', 'admin', await hashPassword(password), 'adm');
  const server = createApp(db);
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); db.close(); rmSync(folder, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (route, method = 'GET', data, cookie, origin) => fetch(base + route, { method, redirect: 'manual', headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}), ...(origin ? { Origin: origin } : {}) }, body: data ? JSON.stringify(data) : undefined });
  assert.equal((await request('/api/session')).status, 401);
  assert.equal((await request('/adm/admin.html')).status, 302);
  assert.equal((await request('/data/book-santos.sqlite')).status, 404);
  assert.equal((await request('/server/index.js')).status, 404);
  assert.equal((await request('/api/login', 'POST', { login: 'admin', senha: 'errada' })).status, 401);
  let response = await request('/api/login', 'POST', { login: 'ADMIN', senha: password });
  assert.equal(response.status, 200);
  assert.match(response.headers.get('set-cookie'), /HttpOnly/);
  const cookie = response.headers.get('set-cookie').split(';')[0];
  assert.equal((await response.json()).password_hash, undefined);
  assert.equal((await request('/adm/admin.html', 'GET', undefined, cookie)).status, 200);
  assert.equal((await request('/api/users', 'POST', { nome: 'Cliente', login: 'cliente', senha: password, funcao: 'cliente' }, cookie, 'https://outro.site')).status, 403);
  assert.equal((await request('/api/users', 'POST', { nome: 'Cliente', login: 'cliente', senha: '123', funcao: 'cliente' }, cookie)).status, 400);
  assert.equal((await request('/api/users', 'POST', { nome: 'Cliente', login: 'cliente', senha: password, funcao: 'cliente' }, cookie)).status, 200);
  assert.equal((await request('/api/users', 'POST', { nome: 'Outro', login: 'cliente', senha: password, funcao: 'cliente' }, cookie)).status, 409);
  response = await request('/api/users', 'GET', undefined, cookie);
  const users = await response.json();
  assert.ok(users.every(user => !('senha' in user) && !('password_hash' in user)));
  const clientId = users.find(user => user.login === 'cliente').id;
  const reader = openDatabase(filename);
  assert.equal(reader.prepare('SELECT COUNT(*) AS total FROM users').get().total, 2);
  reader.close();
  response = await request('/api/login', 'POST', { login: 'cliente', senha: password });
  const clientCookie = response.headers.get('set-cookie').split(';')[0];
  assert.equal((await request('/api/users', 'GET', undefined, clientCookie)).status, 403);
  assert.equal((await request('/adm/admin.html', 'GET', undefined, clientCookie)).status, 302);
  assert.equal((await request('/api/users/master', 'DELETE', undefined, cookie)).status, 403);
  assert.equal((await request('/api/users/' + clientId, 'DELETE', undefined, cookie)).status, 200);
  assert.equal((await request('/api/session', 'GET', undefined, clientCookie)).status, 401);
  assert.equal((await request('/api/logout', 'POST', {}, cookie)).status, 200);
  assert.equal((await request('/api/session', 'GET', undefined, cookie)).status, 401);
  for (let i = 0; i < 10; i++) await request('/api/login', 'POST', { login: 'admin', senha: 'errada' });
  assert.equal((await request('/api/login', 'POST', { login: 'admin', senha: password })).status, 429);
});
